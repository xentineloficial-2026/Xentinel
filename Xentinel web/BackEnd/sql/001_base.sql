-- PostgreSQL 17+. Base nueva sin datos personales. También completa el dump adjunto.
CREATE TABLE IF NOT EXISTS rol (
 id_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre_rol varchar(30) NOT NULL UNIQUE, descripcion_rol text
);
INSERT INTO rol(nombre_rol) SELECT nombre FROM (VALUES ('Aprendiz'),('Instructor'),('Administrador'),('Celador'),('Funcionarios'),('Visitantes')) seed(nombre)
 WHERE NOT EXISTS(SELECT 1 FROM rol WHERE lower(nombre_rol)=lower(seed.nombre));
CREATE TABLE IF NOT EXISTS usuarios (
 id_usuarios integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombres_completos varchar(150) NOT NULL, tipo_documento varchar(10) NOT NULL,
 numero_documento varchar(20) NOT NULL UNIQUE, contrasena varchar(255) NOT NULL,
 correo varchar(254), telefono varchar(20), fecha_nacimiento date,
 id_rol integer NOT NULL REFERENCES rol(id_rol), ambiente varchar(50),
 estado varchar(20) NOT NULL DEFAULT 'Activo', situacion_formativa varchar(20),
 qr_asignado boolean NOT NULL DEFAULT false, qr_url varchar(255), foto_url varchar(255), foto_pos varchar(120)
);
CREATE TABLE IF NOT EXISTS programa (
 id_programa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre_programa varchar(150) NOT NULL, nivel_programa varchar(50)
);
CREATE TABLE IF NOT EXISTS ficha (
 id_ficha integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero_ficha varchar(15) NOT NULL UNIQUE, id_programa integer NOT NULL REFERENCES programa(id_programa),
 jornada varchar(20), modalidad varchar(50), fecha_inicio date, fecha_fin date
);
CREATE TABLE IF NOT EXISTS jornada (
 id_jornada integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_ficha integer NOT NULL REFERENCES ficha(id_ficha), nombre varchar(50) NOT NULL,
 hora_inicio time NOT NULL, hora_fin time NOT NULL
);
CREATE TABLE IF NOT EXISTS aprendiz_ficha (
 id_aprendiz_ficha integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuarios integer NOT NULL REFERENCES usuarios(id_usuarios), id_ficha integer NOT NULL REFERENCES ficha(id_ficha),
 estado varchar(50) NOT NULL, fechaingreso date, fechasalida date
);
CREATE TABLE IF NOT EXISTS instructor_ficha (
 id_instructor_ficha integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuarios integer NOT NULL REFERENCES usuarios(id_usuarios), id_ficha integer NOT NULL REFERENCES ficha(id_ficha),
 fecha_asignacion date DEFAULT CURRENT_DATE, estado varchar(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS estado_aprendiz (
 id_estado_aprendiz_ficha integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuarios integer NOT NULL REFERENCES usuarios(id_usuarios), id_ficha integer NOT NULL REFERENCES ficha(id_ficha),
 fechahoraingreso timestamptz DEFAULT now(), estado varchar(50) NOT NULL
);
CREATE TABLE IF NOT EXISTS horarios (
 id_horario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre_clase varchar(150) NOT NULL, dia_semana varchar(20) NOT NULL,
 hora_inicio time NOT NULL, hora_fin time NOT NULL, ambiente varchar(50),
 id_ficha integer NOT NULL REFERENCES ficha(id_ficha), id_instructor integer NOT NULL REFERENCES usuarios(id_usuarios)
);
CREATE TABLE IF NOT EXISTS acceso (
 id_acceso integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuarios integer NOT NULL REFERENCES usuarios(id_usuarios), tipo varchar(20) NOT NULL,
 fechahora timestamptz NOT NULL DEFAULT now(), metodo varchar(20) NOT NULL, estado varchar(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS asistencia (
 id_asistencia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_usuarios integer NOT NULL REFERENCES usuarios(id_usuarios), id_jornada integer NOT NULL REFERENCES jornada(id_jornada),
 fecha date NOT NULL, hora_entrada time, hora_salida time, estado varchar(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS solicitudes_horario (
 id_solicitud integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_horario integer REFERENCES horarios(id_horario), id_ficha integer NOT NULL REFERENCES ficha(id_ficha),
 id_instructor integer NOT NULL REFERENCES usuarios(id_usuarios), tipo_solicitud varchar(20) NOT NULL DEFAULT 'Modificación',
 nombre_clase varchar(150) NOT NULL, dia_semana_propuesto varchar(20), hora_inicio_propuesta time,
 hora_fin_propuesta time, ambiente_propuesto varchar(50), motivo text NOT NULL,
 estado varchar(20) NOT NULL DEFAULT 'Pendiente', fecha_solicitud timestamptz NOT NULL DEFAULT now(),
 respuesta_admin text, fecha_respuesta timestamptz, id_admin integer REFERENCES usuarios(id_usuarios),
 leida_instructor boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS horario_archivo (
 id_archivo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_ficha integer NOT NULL REFERENCES ficha(id_ficha), id_usuarios integer NOT NULL REFERENCES usuarios(id_usuarios),
 nombre_original varchar(255) NOT NULL, ruta_archivo varchar(255) NOT NULL,
 estado varchar(20) NOT NULL DEFAULT 'Vigente', fecha_subida timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS alertas_emergencia (
 id_alerta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tipo_alerta varchar(50) NOT NULL, mensaje text, activa boolean NOT NULL DEFAULT true,
 fecha_inicio timestamptz NOT NULL DEFAULT now(), fecha_fin timestamptz,
 emisor_id integer NOT NULL REFERENCES usuarios(id_usuarios)
);
CREATE TABLE IF NOT EXISTS reportes_pase_lista (
 id_reporte integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_alerta integer NOT NULL REFERENCES alertas_emergencia(id_alerta),
 id_instructor integer NOT NULL REFERENCES usuarios(id_usuarios), id_ficha integer NOT NULL REFERENCES ficha(id_ficha),
 observaciones text, fecha_envio timestamptz NOT NULL DEFAULT now(),
 estudiantes_presentes text NOT NULL DEFAULT '[]'
);
CREATE TABLE IF NOT EXISTS ubicaciones_sos (
 id_sos integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_alerta integer REFERENCES alertas_emergencia(id_alerta), id_aprendiz integer NOT NULL REFERENCES usuarios(id_usuarios),
 latitud numeric(9,6) NOT NULL, longitud numeric(9,6) NOT NULL, fecha_registro timestamptz NOT NULL DEFAULT now()
);
